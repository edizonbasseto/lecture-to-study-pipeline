"""Export the site image dependency closure with hashes.

Generates ``infra/site-requirements.txt`` from ``uv.lock``: only the
packages the site image installs (fastapi, uvicorn, pyyaml, markdown-it-py,
pydantic) plus their transitive dependencies, each with the hashes ``uv
export --frozen`` records for every wheel and sdist. ``Dockerfile.site``
installs that file with ``--require-hashes``, so a build fails instead of
running unpinned transitive dependencies resolved at build time.

Regenerate after any change to ``uv.lock`` that touches the closure:

    python3 scripts/export_site_requirements.py
"""

from __future__ import annotations

import re
import subprocess
import tomllib
from collections.abc import Iterator
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
LOCK_PATH = REPO_ROOT / "uv.lock"
OUTPUT_PATH = REPO_ROOT / "infra" / "site-requirements.txt"

SITE_ROOTS = ("fastapi", "uvicorn", "pyyaml", "markdown-it-py", "pydantic")

_EXPORT_COMMAND = (
    "uv",
    "export",
    "--frozen",
    "--no-dev",
    "--no-emit-project",
    "--no-header",
    "--no-annotate",
)

_HEADER = """\
# Site image dependencies (Dockerfile.site). Autogenerated; do not edit.
# Regenerate with: python3 scripts/export_site_requirements.py
# Install with: pip install --require-hashes -r site-requirements.txt
"""


def normalized(name: str) -> str:
    """PEP 503-normalize a package name for lock/export comparisons."""
    return re.sub(r"[-_.]+", "-", name).lower()


def lock_dependency_graph() -> dict[str, tuple[str, ...]]:
    """Map every locked package to the names it depends on."""
    with LOCK_PATH.open("rb") as lock_file:
        lock = tomllib.load(lock_file)
    return {
        normalized(package["name"]): tuple(
            normalized(dependency["name"])
            for dependency in package.get("dependencies", [])
        )
        for package in lock["package"]
    }


def dependency_closure(
    graph: dict[str, tuple[str, ...]], roots: tuple[str, ...]
) -> set[str]:
    """Reach every package the roots install, transitively."""
    reached: set[str] = set()
    pending = list(roots)
    while pending:
        name = pending.pop()
        if name in reached:
            continue
        reached.add(name)
        pending.extend(graph.get(name, ()))
    return reached


def exported_requirement_blocks() -> dict[str, str]:
    """Map each exported package name to its full requirements block."""
    export = subprocess.run(
        _EXPORT_COMMAND,
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    blocks: dict[str, str] = {}
    for block in re.split(r"\n(?=[A-Za-z0-9_.-]+==)", export.strip()):
        match = re.match(r"([A-Za-z0-9_.-]+)==", block)
        if match:
            blocks[normalized(match.group(1))] = block.strip().rstrip("\\").strip()
    return blocks


def closure_requirements() -> Iterator[str]:
    graph = lock_dependency_graph()
    closure = dependency_closure(graph, SITE_ROOTS)
    blocks = exported_requirement_blocks()
    missing = sorted(closure - blocks.keys())
    if missing:
        raise SystemExit("uv export is missing closure members: " + ", ".join(missing))
    return (blocks[name] for name in sorted(closure))


def main() -> None:
    requirements = "\n\n".join(closure_requirements()) + "\n"
    OUTPUT_PATH.write_text(_HEADER + requirements, encoding="utf-8")
    count = requirements.count("\n\n") + 1
    print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)}: {count} requirements written")


if __name__ == "__main__":
    main()
